void gfx_clear(void) { memset(oled_fb, 0, sizeof oled_fb); }

/* OR / clear / XOR a vertical run of `bits` (LSB = top) starting at (x, y), byte-wise across pages */
enum { OP_OR, OP_CLR, OP_XOR };
static void col_op(int x, int y, uint32_t bits, int op)
{
    if ((unsigned)x >= OLED_W || !bits) return;
    if (y < 0) { if (y <= -32) return; bits >>= -y; y = 0; }
    if (y >= OLED_H) return;
    int page = y >> 3, sh = y & 7;
    uint64_t v = (uint64_t)bits << sh;
    for (; page < OLED_H / 8 && v; page++, v >>= 8) {
        uint8_t b = (uint8_t)v, *p = &oled_fb[page * OLED_W + x];
        if (op == OP_OR) *p |= b; else if (op == OP_CLR) *p &= (uint8_t)~b; else *p ^= b;
    }
}
static uint32_t run_mask(int h) { return h >= 32 ? 0xFFFFFFFFu : (1u << h) - 1; }

void gfx_pixel(int x, int y, bool on)
{
    if ((unsigned)x >= OLED_W || (unsigned)y >= OLED_H) return;
    uint8_t *p = &oled_fb[(y >> 3) * OLED_W + x], m = (uint8_t)(1u << (y & 7));
    if (on) *p |= m; else *p &= (uint8_t)~m;
}

void gfx_fill(int x, int y, int w, int h, bool on)
{
    if (h <= 0) return;
    for (int i = x; i < x + w; i++) col_op(i, y, run_mask(h), on ? OP_OR : OP_CLR);
}

void gfx_rect(int x, int y, int w, int h)
{
    gfx_fill(x, y, w, 1, 1); gfx_fill(x, y + h - 1, w, 1, 1);
    gfx_fill(x, y, 1, h, 1); gfx_fill(x + w - 1, y, 1, h, 1);
}

void gfx_hline(int x, int y, int w) { gfx_fill(x, y, w, 1, 1); }

void gfx_invert(int x, int y, int w, int h)
{
    if (h <= 0) return;
    for (int i = x; i < x + w; i++) col_op(i, y, run_mask(h), OP_XOR);
}

static uint32_t stretch(uint32_t g, int scale)   /* repeat each bit `scale` times */
{
    if (scale == 1) return g;
    uint32_t r = 0;
    for (int b = 0; b < 8; b++) if (g >> b & 1) r |= run_mask(scale) << (b * scale);
    return r;
}

int gfx_char(int x, int y, char c, int scale)
{
    if (c < 0x20 || c > 0x7E) c = '?';
    const uint8_t *g = FONT5x7[c - 0x20];
    for (int col = 0; col < 5; col++) {
        uint32_t bits = stretch(g[col], scale);
        for (int s = 0; s < scale; s++) col_op(x + col * scale + s, y, bits, OP_OR);
    }
    return 6 * scale;
}

int gfx_text(int x, int y, const char *s, int scale)
{
    while (*s) x += gfx_char(x, y, *s++, scale);
    return x;
}

int gfx_text_gap(int x, int y, const char *s, int scale, int gap)
{
    while (*s) { gfx_char(x, y, *s++, scale); x += 5 * scale + gap; }
    return x;
}

/* the one "value" style: 2x text (spacing 2, 1 or 0 to fit width w), else 1x vertically centred. Returns scale. */
int gfx_text_fit(int x, int y, const char *s, int w)
{
    int n = 0; while (s[n]) n++;
    for (int gap = 2; gap >= 0; gap--)
        if (n * (10 + gap) - gap <= w + 2) { gfx_text_gap(x, y, s, 2, gap); return 2; }   /* last glyph column is usually blank */
    gfx_text(x, y + 4, s, 1); return 1;
}

int gfx_text_width(const char *s, int scale) { int n = 0; while (s[n]) n++; return n * 6 * scale - scale; }

void gfx_text_center(int y, const char *s, int scale) { gfx_text((OLED_W - gfx_text_width(s, scale)) / 2, y, s, scale); }
